# STEP 4: DEFINE THE NEURAL NETWORK ARCHITECTURE

# MODEL B - Sigmoid:
#   Formula: f(x) = 1 / (1 + e^(-x))
#   Squashes any input to a value between 0 and 1.
#   Pros: Smooth, bounded output
#   Cons: Can cause "vanishing gradients" (very slow learning in deep networks)
#
# NETWORK STRUCTURE (same for both models):
# ┌─────────────────┐
# │  Input Layer     │  784 neurons (one per pixel)
# │  (Flatten)       │
# ├─────────────────┤
# │  Hidden Layer 1  │  256 neurons with activation function
# ├─────────────────┤
# │  Hidden Layer 2  │  128 neurons with activation function
# ├─────────────────┤
# │  Hidden Layer 3  │  64 neurons with activation function
# ├─────────────────┤
# │  Output Layer    │  10 neurons (one per digit) with Softmax
# └─────────────────┘
#
# SOFTMAX (output layer): Converts raw scores into probabilities (0-1)
# that sum to 1. The highest probability = the predicted digit.

print("\n>>> STEP 4: Building Neural Network Models...")
print("-" * 60)


def build_model(activation_function, model_name):
    """
    Creates and compiles a neural network model.

    Parameters:
    -----------
    activation_function : str
        The activation function for hidden layers ('relu' or 'sigmoid')
    model_name : str
        A descriptive name for the model

    Returns:
    --------
    model : keras.Sequential
        The compiled (ready-to-train) neural network model
    """

    model = Sequential(name=model_name)
    # Sequential means layers are stacked one after another (like a sandwich)

    # --- Input Layer ---
    # Dense(256) = a fully connected layer with 256 neurons
    # input_shape=(784,) tells the network each input is a flat array of 784 values
    model.add(Dense(256,
                    activation=activation_function,
                    input_shape=(784,),
                    name='hidden_layer_1'))

    # --- Hidden Layer 2 ---
    # 128 neurons, same activation function
    # Note: we don't need input_shape here; Keras infers it from the previous layer
    model.add(Dense(128,
                    activation=activation_function,
                    name='hidden_layer_2'))

    # --- Hidden Layer 3 ---
    # 64 neurons, same activation function
    model.add(Dense(64,
                    activation=activation_function,
                    name='hidden_layer_3'))

    # --- Output Layer ---
    # 10 neurons (one for each digit 0-9)
    # Softmax activation: outputs probabilities that sum to 1
    # Example output: [0.01, 0.02, 0.05, 0.80, 0.01, 0.03, 0.02, 0.03, 0.02, 0.01]
    #                  means 80% confident it's digit "3"
    model.add(Dense(num_classes,
                    activation='softmax',
                    name='output_layer'))

    # --- Compile the Model ---
    # This configures the model for training by specifying:
    #
    # optimizer='adam':
    #   Adam is an advanced optimization algorithm that adjusts learning rate
    #   automatically. It's the most popular choice and works well in most cases.
    #
    # loss='categorical_crossentropy':
    #   This is the loss function - it measures how wrong our predictions are.
    #   'categorical_crossentropy' is designed for multi-class classification
    #   with one-hot encoded labels. Lower loss = better predictions.
    #
    # metrics=['accuracy']:
    #   We also want to track accuracy (% of correct predictions) during training.

    model.compile(
        optimizer='adam',
        loss='categorical_crossentropy',
        metrics=['accuracy']
    )

    return model


