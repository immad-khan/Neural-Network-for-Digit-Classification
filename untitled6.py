# STEP 5: TRAIN BOTH MODELS
# =====================================================================
# Training = showing the network many examples so it learns the patterns.
#
# KEY TRAINING CONCEPTS:
#
# EPOCH: One complete pass through the ENTIRE training dataset.
#   Like reading a textbook cover-to-cover once = 1 epoch.
#   We'll do 20 epochs (read the textbook 20 times).
#
# BATCH SIZE: How many images the network sees before updating its weights.
#   batch_size=128 means: look at 128 images, calculate the average error,
#   then adjust weights. This is more efficient than updating after every
#   single image (too noisy) or after all 60,000 images (too slow).
#
# VALIDATION SPLIT: We reserve 20% of training data to check progress.
#   The network does NOT learn from validation data - it's like a mini-test
#   taken after each epoch to see if the network is truly learning
#   (not just memorizing).
#
# WHAT HAPPENS DURING TRAINING?
#   1. Forward pass: Data flows through the network, prediction is made
#   2. Loss calculation: Compare prediction to actual label
#   3. Backward pass: Calculate how to adjust weights to reduce loss
#   4. Weight update: Adjust weights using the optimizer (Adam)
#   Repeat for every batch, for every epoch.

print("\n>>> STEP 5: Training Both Models...")
print("-" * 60)

# Training hyperparameters (settings that control the training process)
